"""Generate docs/research/EXPERIMENT_STATUS.md from the registry and the
artifacts it cites.

A hand-maintained status table drifts from the results it summarises (the
EVOLUTION 4.49/4.50 failure, in miniature). This one is regenerated:
`python -m echotales.research.aggregate` -- every row is the registry entry
plus the `verdict_hint` of the newest cited `results.json`.
"""

from __future__ import annotations

import json
from pathlib import Path

from echotales.research import registry

ROOT = Path(__file__).resolve().parents[5]
OUT = ROOT / "docs" / "research" / "EXPERIMENT_STATUS.md"
LEVELS = {0: "none", 1: "L1 existing code", 2: "L2 research module", 3: "L3 controlled benchmark",
          4: "L4 human study"}


def _hint(evidence: list[str]) -> str:
    for e in reversed(evidence):
        p = ROOT / e
        if p.suffix == ".json" and p.exists():
            return json.loads(p.read_text()).get("verdict_hint", "")
    return ""


def render() -> str:
    hs = registry.load()
    order = {"SURVIVING": 0, "OPEN": 1, "PARKED": 2, "KILLED": 3}
    lines = [
        "# Experiment status",
        "",
        "Generated by `python -m echotales.research.aggregate` from",
        "`packages/research/src/echotales/research/hypotheses.toml` and the artifacts it cites.",
        "Do not edit by hand; the narrative for each verdict is in `DECISION_LOG.md`.",
        "",
        "| ID | Status | Level reached | Mutation of | Title | Latest machine verdict |",
        "|---|---|---|---|---|---|",
    ]
    for h in sorted(hs.values(), key=lambda h: (order[h.status.value], h.id)):
        hint = _hint(h.evidence).replace("|", "/")
        if len(hint) > 220:
            hint = hint[:217] + "..."
        lines.append(f"| {h.id} | {h.status.value} | {LEVELS.get(h.level, h.level)} | "
                     f"{', '.join(h.mutation_of) or '-'} | {h.title} | {hint or '-'} |")
    counts: dict[str, int] = {}
    for h in hs.values():
        counts[h.status.value] = counts.get(h.status.value, 0) + 1
    lines += ["", "Counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())), ""]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(render())
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
