"""The gazetteer compounding curve, persisted rather than printed and lost.

Non-negotiable #8 says the gazetteer compounds — that the system gets cheaper
and more accurate the deeper into a volume it reads. That is the project's
headline claim about its own architecture, and until 2026-09-23 it was an
assertion: the detection half was computed every run
(`mentions/runner.py::MentionReport.gazetteer_hit_rate_by_window`), printed
into a terminal, and thrown away, and the resolution half did not exist at all
because every link claimed to be `SCORED` (EVOLUTION 4.77).

Both halves are needed and they answer different questions:

- **detection** — of the surfaces found in this window, what share did the
  grown gazetteer match directly rather than the NER model having to find?
  This is the cost half of the claim.
- **resolution** — of the links made in this window, what share were settled
  by `GAZETTEER_EXACT` rather than by the scorer? This is the accuracy half,
  and it is the one an ablation ("no gazetteer compounding") has to move.

The two stages run separately (`detect_mentions` then `resolve_novel`), so
each writes its own half into the same per-novel file and neither clobbers the
other. Keyed by window index, which is `chapter // settings.window_size`.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

#: Curves live beside the other evaluation outputs rather than in the
#: database: they are a few dozen floats, they are regenerated by any rerun,
#: and a reader wants to diff two of them.
#:
#: Overridable by `ECHOTALES_EVAL_ROOT` because `resolve_novel` writes a curve
#: unconditionally, and several existing tests resolve a toy novel called "t"
#: -- which wrote `data/eval/compounding/t.json` into the real repository on
#: every test run until a `conftest.py` pointed this at a temp directory.
#: A stage that writes to a fixed repo path is a stage that cannot be tested
#: without leaving litter behind.
DEFAULT_CURVE_ROOT = Path("data/eval/compounding")


def curve_root() -> Path:
    """Resolved per call, not at import, so a fixture can set it."""
    return Path(os.environ.get("ECHOTALES_EVAL_ROOT", "") or DEFAULT_CURVE_ROOT)


@dataclass(slots=True)
class CompoundingCurve:
    """One novel's compounding evidence, both halves, most recent write wins."""

    novel_id: str
    window_size: int = 0
    #: (window index, share of surfaces matched by the grown gazetteer)
    detection: list[tuple[int, float]] = field(default_factory=list)
    #: (window index, share of links settled by GAZETTEER_EXACT, links in window)
    resolution: list[tuple[int, float, int]] = field(default_factory=list)
    detection_written_at: float = 0.0
    resolution_written_at: float = 0.0

    @staticmethod
    def path_for(novel_id: str, root: Path | None = None) -> Path:
        return (root or curve_root()) / f"{novel_id}.json"

    @classmethod
    def load(cls, novel_id: str, root: Path | None = None) -> CompoundingCurve:
        path = cls.path_for(novel_id, root)
        if not path.exists():
            return cls(novel_id=novel_id)
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            # A corrupt curve is worth strictly less than the run that is
            # about to overwrite it; losing it is not a reason to fail a
            # 199-chapter resolve.
            return cls(novel_id=novel_id)
        return cls(
            novel_id=data.get("novel_id", novel_id),
            window_size=data.get("window_size", 0),
            detection=[tuple(row) for row in data.get("detection", [])],  # type: ignore[misc]
            resolution=[tuple(row) for row in data.get("resolution", [])],  # type: ignore[misc]
            detection_written_at=data.get("detection_written_at", 0.0),
            resolution_written_at=data.get("resolution_written_at", 0.0),
        )

    def write(self, root: Path | None = None) -> Path:
        path = self.path_for(self.novel_id, root)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(asdict(self), indent=2, sort_keys=True), encoding="utf-8")
        return path

    def summary(self) -> str:
        """One line per half, shaped so a rise or a flat line is visible."""
        lines: list[str] = []
        if self.detection:
            points = " ".join(f"w{w}={rate:.0%}" for w, rate in self.detection)
            lines.append(f"  gazetteer compounding (detection): {points}")
        if self.resolution:
            points = " ".join(f"w{w}={rate:.0%}(n={n})" for w, rate, n in self.resolution)
            lines.append(f"  gazetteer compounding (resolution): {points}")
        return "\n".join(lines)


def record_detection_half(
    novel_id: str,
    *,
    window_size: int,
    points: list[tuple[int, float]],
    root: Path | None = None,
) -> Path:
    curve = CompoundingCurve.load(novel_id, root)
    curve.window_size = window_size or curve.window_size
    curve.detection = list(points)
    curve.detection_written_at = time.time()
    return curve.write(root)


def record_resolution_half(
    novel_id: str,
    *,
    window_size: int,
    by_window: dict[int, dict[str, int]],
    method: str = "GAZETTEER_EXACT",
    root: Path | None = None,
) -> Path:
    """Reduce per-window method counts to a share-settled-by-`method` curve.

    Deliberately keeps the window's link count alongside the rate: an early
    window with four links at 100% is not evidence of anything, and a rate
    printed without its denominator invites exactly that reading.
    """
    curve = CompoundingCurve.load(novel_id, root)
    curve.window_size = window_size or curve.window_size
    points: list[tuple[int, float, int]] = []
    for window in sorted(by_window):
        counts = by_window[window]
        total = sum(counts.values())
        points.append((window, counts.get(method, 0) / total if total else 0.0, total))
    curve.resolution = points
    curve.resolution_written_at = time.time()
    return curve.write(root)
