def J(p):
    return json.loads(Path(p).read_text())


def tex(s) -> str:
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(ch, ch) for ch in str(s))


def pc(x, d=1):
    return f"{100 * x:.{d}f}"


def pts(x, d=1):
    return f"{100 * x:+.{d}f}"


def ci(lo, hi):
    return f"[{100 * lo:+.1f}, {100 * hi:+.1f}]"


def table(caption, label, spec, header, rows, size=r"\footnotesize"):
    out = [r"\begin{table}[!ht]", r"\centering", size, rf"\caption{{{caption}}}\label{{{label}}}",
           rf"\begin{{tabular}}{{{spec}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    out += [" & ".join(str(c) for c in r) + r" \\" for r in rows]
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(out)


def unformat(template: str) -> str:
    """str.format templates escape literal braces as {{ }}; the model received single braces."""
    return template.replace("{{", "{").replace("}}", "}")


def prompt_block(title, text):
    body = "\\\\\n".join(tex(line) if line.strip() else r"\mbox{}" for line in text.split("\n"))
    return "\n".join([rf"\paragraph{{{tex(title)}}}", r"\begin{quote}\small\ttfamily\raggedright\sloppy", body, r"\end{quote}", ""])


